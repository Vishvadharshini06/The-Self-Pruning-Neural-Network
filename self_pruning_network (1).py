# Part 1: PrunableLinear Layer  (fixed)

class PrunableLinear(nn.Module):
    """
    Linear layer with per-weight learnable gates.

    forward:
        gates         = sigmoid(gate_scores)        ∈ (0, 1)
        pruned_weight = weight ⊙ gates
        output        = x @ pruned_weight.T + bias

    FIX vs v1:
        gate_scores initialised to 0.0  →  sigmoid(0) = 0.5
        This puts gates in the steepest part of the sigmoid where
        gradients are largest, making L1 pressure effective immediately.
        (v1 used 2.0 → sigmoid ≈ 0.88, very hard to push to 0)
    """

    def __init__(self, in_features: int, out_features: int, bias: bool = True):
        super().__init__()
        self.in_features  = in_features
        self.out_features = out_features

        self.weight      = nn.Parameter(torch.empty(out_features, in_features))
        self.bias        = nn.Parameter(torch.zeros(out_features)) if bias else None

        # KEY FIX: init at 0 not 2 → sigmoid(0)=0.5, maximum gradient region
        self.gate_scores = nn.Parameter(torch.zeros(out_features, in_features))

        nn.init.kaiming_uniform_(self.weight, a=0.01)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        gates         = torch.sigmoid(self.gate_scores)   # (out, in)
        pruned_weight = self.weight * gates
        return F.linear(x, pruned_weight, self.bias)

    # ── helpers ───────────────────────────────────────────────────────────────

    def get_gates(self) -> torch.Tensor:
        return torch.sigmoid(self.gate_scores).detach().cpu()

    def sparsity_fraction(self, threshold: float = 1e-2) -> float:
        return (self.get_gates() < threshold).float().mean().item()

    def extra_repr(self) -> str:
        return f"in={self.in_features}, out={self.out_features}"



# Part 2: Network — CNN backbone + prunable classifier head

class SelfPruningCNN(nn.Module):
    """
    Architecture
    ────────────
    CNN Backbone (standard conv layers, NOT pruned):
        Conv(3→64)  → BN → ReLU → MaxPool
        Conv(64→128)→ BN → ReLU → MaxPool
        Conv(128→256)→BN → ReLU → MaxPool
        AdaptiveAvgPool → 256-d feature vector

    Prunable Classifier Head:
        PrunableLinear(256 → 512) → BN → ReLU → Dropout
        PrunableLinear(512 → 256) → BN → ReLU → Dropout
        PrunableLinear(256 → 10)

    Why split CNN + prunable head?
        Conv layers are already parameter-efficient.
        The dense classifier is where redundancy lives — pruning it
        gives meaningful sparsity without destroying feature extraction.
    """

    def __init__(self, dropout: float = 0.4):
        super().__init__()

        # CNN backbone
        def conv_block(in_ch, out_ch):
            return nn.Sequential(
                nn.Conv2d(in_ch, out_ch, kernel_size=3, padding=1, bias=False),
                nn.BatchNorm2d(out_ch),
                nn.ReLU(inplace=True),
                nn.Conv2d(out_ch, out_ch, kernel_size=3, padding=1, bias=False),
                nn.BatchNorm2d(out_ch),
                nn.ReLU(inplace=True),
                nn.MaxPool2d(2),
            )

        self.backbone = nn.Sequential(
            conv_block(3,   64),   # 32→16
            conv_block(64,  128),  # 16→8
            conv_block(128, 256),  # 8→4
            nn.AdaptiveAvgPool2d(1),  # 4→1  →  256-d vector
            nn.Flatten(),
        )

        # Prunable classifier head
        self.head = nn.Sequential(
            PrunableLinear(256, 512),
            nn.BatchNorm1d(512),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),

            PrunableLinear(512, 256),
            nn.BatchNorm1d(256),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),

            PrunableLinear(256, 10),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        features = self.backbone(x)
        return self.head(features)

    # ── Gate / sparsity helpers ───────────────────────────────────────────────

    def prunable_layers(self) -> list[PrunableLinear]:
        return [m for m in self.modules() if isinstance(m, PrunableLinear)]

    def sparsity_loss(self) -> torch.Tensor:
        """Sum of all sigmoid-gate values (L1, since gates ≥ 0)."""
        return torch.cat([
            torch.sigmoid(l.gate_scores).view(-1)
            for l in self.prunable_layers()
        ]).sum()

    def overall_sparsity(self, threshold: float = 1e-2) -> float:
        total = pruned = 0
        for l in self.prunable_layers():
            g = l.get_gates()
            total  += g.numel()
            pruned += (g < threshold).sum().item()
        return 100.0 * pruned / total if total else 0.0

    def all_gate_values(self) -> np.ndarray:
        return np.concatenate([
            l.get_gates().numpy().ravel() for l in self.prunable_layers()
        ])


