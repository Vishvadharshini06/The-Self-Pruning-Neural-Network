def train_one_epoch(model, loader, optimizer, lambda_sparse, device, warmup: bool):
    """
    warmup=True  → sparsity loss is NOT applied (network learns to classify first).
    warmup=False → full loss = CrossEntropy + λ·SparsityLoss.
    """
    model.train()
    tot_sum = cls_sum = spr_sum = 0.0

    for images, labels in loader:
        images, labels = images.to(device), labels.to(device)
        optimizer.zero_grad()

        logits   = model(images)
        cls_loss = F.cross_entropy(logits, labels)

        if warmup:
            loss     = cls_loss
            spr_loss = torch.tensor(0.0)
        else:
            spr_loss = model.sparsity_loss()
            loss     = cls_loss + lambda_sparse * spr_loss

        loss.backward()
        # Clip gradients to stabilise training
        nn.utils.clip_grad_norm_(model.parameters(), max_norm=5.0)
        optimizer.step()

        n = images.size(0)
        tot_sum += loss.item()     * n
        cls_sum += cls_loss.item() * n
        spr_sum += spr_loss.item() * n

    N = len(loader.dataset)
    return tot_sum / N, cls_sum / N, spr_sum / N


@torch.no_grad()
def evaluate(model, loader, device):
    model.eval()
    correct = total = 0
    for images, labels in loader:
        images, labels = images.to(device), labels.to(device)
        correct += (model(images).argmax(1) == labels).sum().item()
        total   += labels.size(0)
    return 100.0 * correct / total


def build_optimizer(model, lr_main=1e-3, lr_gate=5e-3, wd=1e-4):
    """
    Separate parameter groups:
      • gate_scores  → higher LR so they respond quickly to sparsity pressure
      • everything else → standard LR
    """
    gate_params  = [p for n, p in model.named_parameters() if "gate_scores" in n]
    other_params = [p for n, p in model.named_parameters() if "gate_scores" not in n]
    return optim.Adam([
        {"params": other_params, "lr": lr_main, "weight_decay": wd},
        {"params": gate_params,  "lr": lr_gate, "weight_decay": 0.0},
    ])


def train_and_evaluate(
    lambda_sparse: float,
    train_loader,
    test_loader,
    device,
    num_epochs:   int   = 60,
    warmup_epochs: int  = 10,   # pure classification before sparsity kicks in
    verbose:      bool  = True,
) -> tuple[float, float, SelfPruningCNN]:

    model     = SelfPruningCNN().to(device)
    optimizer = build_optimizer(model)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=num_epochs)

    if verbose:
        n_prunable = sum(l.weight.numel() for l in model.prunable_layers())
        print(f"\n{'='*65}")
        print(f"  λ = {lambda_sparse}  |  Prunable weights: {n_prunable:,}"
              f"  |  Warmup: {warmup_epochs} epochs")
        print(f"{'='*65}")
        print(f"{'Ep':>4}  {'TotLoss':>8}  {'ClsLoss':>8}  "
              f"{'SprLoss':>8}  {'Sparsity':>9}  {'Phase':>8}")
        print("-" * 55)

    for epoch in range(1, num_epochs + 1):
        is_warmup = epoch <= warmup_epochs
        tot, cls, spr = train_one_epoch(
            model, train_loader, optimizer, lambda_sparse, device, warmup=is_warmup)
        scheduler.step()

        if verbose and (epoch % 5 == 0 or epoch == 1):
            sparsity = model.overall_sparsity()
            phase    = "WARMUP" if is_warmup else "PRUNE"
            print(f"{epoch:>4}  {tot:>8.4f}  {cls:>8.4f}  "
                  f"{spr:>8.1f}  {sparsity:>8.1f}%  {phase:>8}")

    test_acc = evaluate(model, test_loader, device)
    sparsity = model.overall_sparsity()

    if verbose:
        print(f"\n  ✔  Test Accuracy : {test_acc:.2f}%")
        print(f"  ✔  Sparsity Level: {sparsity:.1f}%")

    return test_acc, sparsity, model



# Plotting


def plot_gate_distribution(model: SelfPruningCNN, lambda_val: float,
                           save_path: str = "gate_distribution.png"):
    gates    = model.all_gate_values()
    sparsity = model.overall_sparsity()

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))

    # Left: full distribution
    axes[0].hist(gates, bins=100, color="#2196F3", edgecolor="white", lw=0.3)
    axes[0].axvline(0.01, color="#F44336", ls="--", lw=1.5, label="Threshold 0.01")
    pct = (gates < 0.01).mean() * 100
    axes[0].set_title(f"All gate values  (λ={lambda_val})", fontsize=12)
    axes[0].set_xlabel("Gate value  σ(score)")
    axes[0].set_ylabel("Count")
    axes[0].text(0.55, 0.92, f"Pruned: {pct:.1f}%\nSparsity: {sparsity:.1f}%",
                 transform=axes[0].transAxes, fontsize=10,
                 bbox=dict(boxstyle="round", fc="lightyellow", alpha=0.9))
    axes[0].legend()

    # Right: zoom into [0, 0.1] to show the spike at 0
    axes[1].hist(gates[gates < 0.1], bins=60, color="#4CAF50", edgecolor="white", lw=0.3)
    axes[1].axvline(0.01, color="#F44336", ls="--", lw=1.5, label="Threshold 0.01")
    axes[1].set_title(f"Zoom: gates < 0.1  (λ={lambda_val})", fontsize=12)
    axes[1].set_xlabel("Gate value")
    axes[1].set_ylabel("Count")
    axes[1].legend()

    plt.suptitle("Self-Pruning Network — Gate Value Distribution", fontsize=13, y=1.01)
    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    print(f"\n  Plot saved → {save_path}")
    plt.show()


def plot_all_distributions(results, save_path="all_gate_distributions.png"):
    """One subplot per λ value for easy comparison."""
    fig, axes = plt.subplots(1, len(results), figsize=(6 * len(results), 5))
    if len(results) == 1:
        axes = [axes]

    for ax, (lam, acc, sparsity, model) in zip(axes, results):
        gates = model.all_gate_values()
        ax.hist(gates, bins=80, color="#2196F3", edgecolor="white", lw=0.2)
        ax.axvline(0.01, color="#F44336", ls="--", lw=1.2)
        ax.set_title(f"λ = {lam:.0e}\nAcc={acc:.1f}%  Sparse={sparsity:.1f}%", fontsize=11)
        ax.set_xlabel("Gate value")
        ax.set_ylabel("Count")

    plt.suptitle("Gate Distributions for all λ values", fontsize=13)
    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    print(f"  Comparison plot saved → {save_path}")
    plt.show()



# Main


def main():
    # Force CPU if CUDA version is incompatible (e.g., P100 on old PyTorch)
    if torch.cuda.is_available():
        try:
            torch.zeros(1).cuda()          # quick smoke test
            device = torch.device("cuda")
        except Exception:
            print("CUDA unavailable (incompatible GPU) — falling back to CPU")
            device = torch.device("cpu")
    else:
        device = torch.device("cpu")

    print(f"Device: {device}\n")

    train_loader, test_loader = get_cifar10_loaders(batch_size=128)

    # Three λ values covering low / medium / high sparsity pressure
    lambdas = [1e-3, 1e-2, 1e-1]

    results   = []
    best_model = best_lambda = None
    best_score = -1e9

    for lam in lambdas:
        acc, sparsity, model = train_and_evaluate(
            lambda_sparse  = lam,
            train_loader   = train_loader,
            test_loader    = test_loader,
            device         = device,
            num_epochs     = 60,
            warmup_epochs  = 10,
        )
        results.append((lam, acc, sparsity, model))

        score = acc - 0.1 * sparsity
        if score > best_score:
            best_score = score
            best_model = model
            best_lambda = lam

    # ── Summary ───────────────────────────────────────────────────────────────
    print("\n\n" + "=" * 55)
    print("  RESULTS SUMMARY")
    print("=" * 55)
    print(f"{'Lambda':>10}  {'Test Accuracy':>14}  {'Sparsity (%)':>13}")
    print("-" * 45)
    for lam, acc, sparsity, _ in results:
        print(f"{lam:>10.1e}  {acc:>13.2f}%  {sparsity:>12.1f}%")
    print("=" * 55)

    # ── Markdown table ────────────────────────────────────────────────────────
    print("\n\n| Lambda | Test Accuracy (%) | Sparsity Level (%) |")
    print("|--------|-------------------|--------------------|")
    for lam, acc, sparsity, _ in results:
        print(f"| {lam:.1e} | {acc:.2f}             | {sparsity:.1f}               |")

    # Plots ─────────────────────────────────────────────────────────────────
    plot_gate_distribution(best_model, best_lambda, "gate_distribution_best.png")
    plot_all_distributions(results, "all_gate_distributions.png")


if __name__ == "__main__":
    main()